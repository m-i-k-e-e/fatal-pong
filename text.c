#define GLYPH_COUNT (int)(sizeof(FONT_5x7) / sizeof(FONT_5x7[0]))

// NULL for spaces and unsupported characters, which are drawn as blanks
static const Glyph *find_glyph(char c) {
    c = (char)toupper((unsigned char)c);
    for (int i = 0; i < GLYPH_COUNT; i++) if (FONT_5x7[i].c == c) return &FONT_5x7[i];
    return NULL;
}

// Copy a character's 7 rows (5 bits each, MSB on the left) into `rows`; false, with blank rows, if the font
// lacks it
bool text_glyph(char c, unsigned char rows[GLYPH_H]) {
    const Glyph *g = find_glyph(c);
    for (int r = 0; r < GLYPH_H; r++) rows[r] = g ? g->rows[r] : 0;
    return g != NULL;
}

// Width in pixels of `s` drawn at `scale` (letters are 5 wide plus 1 of spacing, none after the last)
int text_width(const char *s, int scale) {
    int n = 0;
    while (s[n]) n++;
    return n > 0 ? (n * (GLYPH_W + 1) - 1) * scale : 0;
}

// Draw `s` with its top-left at (x, y) in the current color; unknown characters leave a gap
int draw_text(SDL_Renderer *renderer, const char *s, int x, int y, int scale) {
    int cur_x = x;
    for (; *s; s++) {
        const Glyph *g = find_glyph(*s);
        if (g) {
            for (int r = 0; r < GLYPH_H; r++) {
                for (int c = 0; c < GLYPH_W; c++) {
                    if ((g->rows[r] >> (GLYPH_W - 1 - c)) & 1) {
                        SDL_Rect rect = { cur_x + c * scale, y + r * scale, scale, scale };
                        SDL_RenderFillRect(renderer, &rect);
                    }
                }
            }
        }
        cur_x += (GLYPH_W + 1) * scale;
    }
    return cur_x - x;
}

// Draw `s` centered on center_x
void draw_text_centered(SDL_Renderer *renderer, const char *s, int center_x, int y, int scale) {
    draw_text(renderer, s, center_x - text_width(s, scale) / 2, y, scale);
}
